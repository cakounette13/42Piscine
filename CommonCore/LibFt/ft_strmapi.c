#include "libft.h"

char	*ft_strmapi(char const *s, char (*f)(unsigned int, char))
{
	char			*new_str;
	int				len_s;
	unsigned int	i;

	if (s == NULL || f == NULL)
		return (NULL);
	len_s = ft_strlen(s);
	new_str = malloc(sizeof(char) * (len_s + 1));
	if (new_str == NULL)
		return (NULL);
	i = 0;
	while (s[i] != '\0')
	{
		new_str[i] = f(i, s[i]);
		i++;
	}
	new_str[i] = '\0';
	return (new_str);
}
